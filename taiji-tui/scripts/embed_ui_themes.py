#!/usr/bin/env python3
"""Generate C++ sources with embedded .theme stylesheet text."""

from __future__ import annotations

import sys
from pathlib import Path


def sanitize_id(theme_id: str) -> str:
    out = []
    for ch in theme_id:
        if ch.isalnum() or ch in "-_":
            out.append(ch)
        else:
            out.append("_")
    return "".join(out) or "theme"


def main() -> int:
    if len(sys.argv) < 4:
        print("usage: embed_ui_themes.py <themes_dir> <output.cpp> <theme_id>...", file=sys.stderr)
        return 1

    themes_dir = Path(sys.argv[1])
    output_path = Path(sys.argv[2])
    theme_ids = sys.argv[3:]

    lines: list[str] = [
        "// Generated by scripts/embed_ui_themes.py. Do not edit.",
        '#include "ui_themes_bundled.hpp"',
        "",
        "namespace ui_bundled_themes {",
        "",
    ]

    entries: list[str] = []
    for theme_id in theme_ids:
        path = themes_dir / f"{theme_id}.theme"
        if not path.is_file():
            print(f"missing theme file: {path}", file=sys.stderr)
            return 1
        text = path.read_text(encoding="utf-8")
        sym = sanitize_id(theme_id)
        lines.append(f'const char kThemeText_{sym}[] = R"tuinator_theme({text})tuinator_theme";')
        lines.append(f'const char kThemeId_{sym}[] = "{theme_id}";')
        lines.append("")
        entries.append(sym)

    lines.append("const BundledTheme kBundledThemes[] = {")
    for sym in entries:
        lines.append(f'    {{kThemeId_{sym}, kThemeText_{sym}}},')
    lines.append("};")
    lines.append("")
    lines.append(f"const std::size_t kBundledThemeCount = {len(entries)};")
    lines.append("")
    lines.append("} // namespace ui_bundled_themes")
    lines.append("")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
